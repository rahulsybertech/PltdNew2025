package com.syber.ssspltd.model.scheme.scheme_detail;

public class SchemeDetails {

    private String id;
    private String salePartyName;
    private String nickName;
    private String saleBillNo;
    private String customerName;
    private String supplierName;
    private String purchaseSno;
    private double saleAmount;
    private int discount;
    private double discountAmount;
    private String nickNameId;

    public String getId() {
        return id;
    }

    public void setId(String id) {
        this.id = id;
    }

    public String getSalePartyName() {
        return salePartyName;
    }

    public void setSalePartyName(String salePartyName) {
        this.salePartyName = salePartyName;
    }

    public String getNickName() {
        return nickName;
    }

    public void setNickName(String nickName) {
        this.nickName = nickName;
    }

    public String getSaleBillNo() {
        return saleBillNo;
    }

    public void setSaleBillNo(String saleBillNo) {
        this.saleBillNo = saleBillNo;
    }

    public String getCustomerName() {
        return customerName;
    }

    public void setCustomerName(String customerName) {
        this.customerName = customerName;
    }

    public String getSupplierName() {
        return supplierName;
    }

    public void setSupplierName(String supplierName) {
        this.supplierName = supplierName;
    }

    public String getPurchaseSno() {
        return purchaseSno;
    }

    public void setPurchaseSno(String purchaseSno) {
        this.purchaseSno = purchaseSno;
    }

    public double getSaleAmount() {
        return saleAmount;
    }

    public void setSaleAmount(double saleAmount) {
        this.saleAmount = saleAmount;
    }

    public int getDiscount() {
        return discount;
    }

    public void setDiscount(int discount) {
        this.discount = discount;
    }

    public double getDiscountAmount() {
        return discountAmount;
    }

    public void setDiscountAmount(double discountAmount) {
        this.discountAmount = discountAmount;
    }

    public String getNickNameId() {
        return nickNameId;
    }

    public void setNickNameId(String nickNameId) {
        this.nickNameId = nickNameId;
    }
}
